from dataclasses import dataclass
import math
import torch
import torch.nn as nn
from torch.nn import functional as F

@dataclass
class GPTConfig:
    block_size: int = 1024   # en fazla kaç token geriye bakılabiliyor
    vocab_size: int = 50257  # token sayısı
    n_layer: int = 12        # blok sayısı
    n_head: int = 12         # her bloktaki head sayısı
    n_embd: int = 768        # her token'ın vektör boyutu


#Attention modeli
class CausalSelfAttention(nn.Module):

    def __init__(self, config):
        super().__init__()
        self.c_attn = nn.Linear(config.n_embd, 3 * config.n_embd)  # q, k, v: üçü birden
        self.c_proj = nn.Linear(config.n_embd, config.n_embd)      # head'leri karıştıran katman
        self.n_head = config.n_head
        self.n_embd = config.n_embd
        tril = torch.tril(torch.ones(config.block_size, config.block_size))
        self.register_buffer("tril", tril.view(1, 1, config.block_size, config.block_size), persistent=False)

    def forward(self, x):
        B, T, C = x.size()                       # C = n_embd = 768
        hs = C // self.n_head                    # head_size = 768 / 12 = 64

        q, k, v = self.c_attn(x).split(self.n_embd, dim=2)   # her biri (B, T, 768)

        # 768 sayıyı 12 head'e böl ve head'i öne al
        q = q.view(B, T, self.n_head, hs).transpose(1, 2)    # (B, 12, T, 64)
        k = k.view(B, T, self.n_head, hs).transpose(1, 2)
        v = v.view(B, T, self.n_head, hs).transpose(1, 2)

        wei = (q @ k.transpose(-2, -1)) * (1.0 / math.sqrt(hs))        # (B, 12, T, T)
        wei = wei.masked_fill(self.tril[:, :, :T, :T] == 0, float("-inf"))
        wei = F.softmax(wei, dim=-1)
        y = wei @ v                                                    # (B, 12, T, 64)

        # 12 head'in çıktısını tekrar yan yana koy
        y = y.transpose(1, 2).contiguous().view(B, T, C)               # (B, T, 768)
        return self.c_proj(y)

#MLP
class MLP(nn.Module):

    def __init__(self, config):
        super().__init__()
        self.c_fc = nn.Linear(config.n_embd, 4 * config.n_embd)    # 768 → 3072
        self.gelu = nn.GELU(approximate="tanh")
        self.c_proj = nn.Linear(4 * config.n_embd, config.n_embd)  # 3072 → 768

    def forward(self, x):
        return self.c_proj(self.gelu(self.c_fc(x)))


#Block
class Block(nn.Module):

    def __init__(self, config):
        super().__init__()
        self.ln_1 = nn.LayerNorm(config.n_embd)
        self.attn = CausalSelfAttention(config)
        self.ln_2 = nn.LayerNorm(config.n_embd)
        self.mlp = MLP(config)

    def forward(self, x):
        x = x + self.attn(self.ln_1(x))   # iletişim
        x = x + self.mlp(self.ln_2(x))    # hesaplama
        return x


#Model
class GPT(nn.Module):

    def __init__(self, config):
        super().__init__()
        self.config = config
        self.transformer = nn.ModuleDict(dict(
            wte = nn.Embedding(config.vocab_size, config.n_embd),   # token tablosu
            wpe = nn.Embedding(config.block_size, config.n_embd),   # pozisyon tablosu
            h = nn.ModuleList([Block(config) for _ in range(config.n_layer)]),  # 12 blok
            ln_f = nn.LayerNorm(config.n_embd),
        ))
        self.lm_head = nn.Linear(config.n_embd, config.vocab_size, bias=False)

    def forward(self, idx, targets=None):
        B, T = idx.size()
        pos = torch.arange(0, T, dtype=torch.long, device=idx.device)
        x = self.transformer.wte(idx) + self.transformer.wpe(pos)   # (B, T, 768)
        for block in self.transformer.h:
            x = block(x)
        x = self.transformer.ln_f(x)
        logits = self.lm_head(x)                                    # (B, T, 50257)

        loss = None
        if targets is not None:
            loss = F.cross_entropy(logits.view(-1, logits.size(-1)), targets.view(-1))
        return logits, loss

#Ağırlıkları yüklemek
from transformers import GPT2LMHeadModel

def load_gpt2_weights(model):
    #hugging face'teki gpt-2 ağırlıklarını kendi modelimize kopyalıyor
    model_hf = GPT2LMHeadModel.from_pretrained("gpt2")
    sd_hf = model_hf.state_dict()   # hugging face'in ağırlıkları: isim -> tensör
    sd = model.state_dict()          # bizim modelin ağırlıkları: isim -> tensör

    # hugging face'te varsa öğrenilmeyen maske tensörlerini atla
    keys_hf = [k for k in sd_hf if not k.endswith(".attn.bias") and not k.endswith(".attn.masked_bias")]

    # bu dört ağırlık hugging face'te ters (transpoze) saklanıyor
    transposed = ["attn.c_attn.weight", "attn.c_proj.weight", "mlp.c_fc.weight", "mlp.c_proj.weight"]

    assert len(keys_hf) == len(sd), f"ağırlık sayıları farklı: {len(keys_hf)} != {len(sd)}" #ağırlık sayıları ve boyutları eşit mi diye kontrol ediyoruz.
    for k in keys_hf:
        with torch.no_grad():
            if any(k.endswith(w) for w in transposed):
                assert sd_hf[k].shape[::-1] == sd[k].shape   # boyutlar ters olmalı
                sd[k].copy_(sd_hf[k].t())                     # çevirip kopyala
            else:
                assert sd_hf[k].shape == sd[k].shape         # boyutlar aynı olmalı
                sd[k].copy_(sd_hf[k])                         # olduğu gibi kopyala
    return model_hf

