def generate_text(model, prompt, max_new_tokens=30, num_samples=3, top_k=50):

    tokens = enc.encode(prompt)
    idx = torch.tensor(tokens, dtype=torch.long, device=device)
    idx = idx.unsqueeze(0).repeat(num_samples, 1)      # (num_samples, T): aynı başlangıçtan 3 kopya

    for _ in range(max_new_tokens):
        idx_cond = idx[:, -model.config.block_size:]     # en fazla 1024 token geriye bak
        with torch.no_grad():
            logits, _ = model(idx_cond)
        logits = logits[:, -1, :]                         # sadece son token'ın skorları: (num_samples, 50257)
        probs = F.softmax(logits, dim=-1)

        topk_probs, topk_ids = torch.topk(probs, top_k, dim=-1)   # en olası 50: (num_samples, 50)
        choice = torch.multinomial(topk_probs, num_samples=1)      # 50'nin içinden birini seç (0-49 arası sıra)
        next_id = torch.gather(topk_ids, -1, choice)               # o sıradaki gerçek token numarası
        idx = torch.cat((idx, next_id), dim=1)

    for i in range(num_samples):
        print(">", enc.decode(idx[i].tolist()))

