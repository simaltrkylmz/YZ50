import tiktoken

class DataLoaderLite:
    #metni token'lara çevirip sırayla B x T'lik batch'ler veriyor

    def __init__(self, B, T):
        self.B, self.T = B, T
        with open("input.txt", "r", encoding="utf-8") as f:
            text = f.read()
        enc = tiktoken.get_encoding("gpt2")
        self.tokens = torch.tensor(enc.encode(text))      # bütün metin, token olarak
        print(f"{len(self.tokens):,} token yüklendi")
        print(f"1 epoch = {len(self.tokens) // (B * T)} batch")
        self.current_position = 0                         # metinde nerede olduğumuz

    def next_batch(self):
        B, T = self.B, self.T
        buf = self.tokens[self.current_position : self.current_position + B * T + 1]
        x = buf[:-1].view(B, T)       # girdi
        y = buf[1:].view(B, T)        # hedef: bir token sağa kaymış hâli
        self.current_position += B * T                    # bir sonraki parçaya geç
        if self.current_position + B * T + 1 > len(self.tokens):
            self.current_position = 0                     # metin bitti, başa dön
        return x, y

