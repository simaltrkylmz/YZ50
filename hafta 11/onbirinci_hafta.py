import time

def benchmark(model, steps=20, use_fp16=False):
    #modeli steps adım eğitip her adımın süresini ölçüyor, ilk 5 adım hariç ortalamayı döndürüyor
    optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4)
    scaler = torch.amp.GradScaler("cuda", enabled=use_fp16)   # şimdilik kapalı, float16'da açacağız
    loader = DataLoaderLite(B=4, T=512)
    times = []

    for i in range(steps):
        t0 = time.time()
        x, y = loader.next_batch()
        x, y = x.to(device), y.to(device)
        optimizer.zero_grad()
        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=use_fp16):
            logits, loss = model(x, y)
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()
        torch.cuda.synchronize()                 # gpu bitirene kadar bekle
        dt = time.time() - t0
        times.append(dt)
        print(f"adım {i:2d} | loss: {loss.item():.4f} | {dt*1000:.0f} ms | {loader.B * loader.T / dt:,.0f} token/s")

    avg = sum(times[5:]) / len(times[5:])       # ilk 5 adım ısınma, sayılmıyor
    print(f"\nortalama (ilk 5 adım hariç): {avg*1000:.0f} ms | {loader.B * loader.T / avg:,.0f} token/s")
    return avg

